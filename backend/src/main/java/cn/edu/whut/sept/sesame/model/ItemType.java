/**
 * 该枚举定义“芝麻开门”后端中的物品类型。
 * 物品类型用于区分宝物、补给、装备和钥匙等不同玩法对象。
 *
 * ItemType 枚举会被 Item 模型使用，后续服务层可以根据类型决定物品是否可使用、
 * 是否计入得分或是否用于开启特殊区域。
 *
 * @author 谢恺燊
 * @version 1.0
 */
package cn.edu.whut.sept.sesame.model;

/**
 * 表示游戏中的物品类型。
 */
public enum ItemType {

    /**
     * 宝物类物品，通常用于计算最终收益或通关评价。
     */
    TREASURE,

    /**
     * 补给类物品，通常用于恢复体力。
     */
    SUPPLY,

    /**
     * 装备类物品，通常用于提升负重能力。
     */
    EQUIPMENT,

    /**
     * 钥匙类物品，通常用于开启特殊房间或机关。
     */
    KEY
}
